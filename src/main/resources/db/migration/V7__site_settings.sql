CREATE TABLE site_settings (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_name               VARCHAR(120) NOT NULL,
    logo_url                VARCHAR(500),
    contact_email           VARCHAR(150),
    contact_phone           VARCHAR(30),
    currency                VARCHAR(3) NOT NULL DEFAULT 'PEN',
    low_stock_threshold     INT NOT NULL DEFAULT 5,
    free_shipping_threshold DECIMAL(10, 2),
    tax_rate                DECIMAL(5, 2) NOT NULL DEFAULT 0,
    shipping_flat_rate      DECIMAL(10, 2) NOT NULL DEFAULT 0,
    updated_at              TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_site_settings_currency CHECK (currency IN ('PEN', 'USD', 'EUR')),
    CONSTRAINT ck_site_settings_low_stock CHECK (low_stock_threshold >= 0),
    CONSTRAINT ck_site_settings_free_shipping CHECK (
        free_shipping_threshold IS NULL OR free_shipping_threshold >= 0),
    CONSTRAINT ck_site_settings_tax CHECK (tax_rate >= 0 AND tax_rate <= 100),
    CONSTRAINT ck_site_settings_shipping CHECK (shipping_flat_rate >= 0)
);

